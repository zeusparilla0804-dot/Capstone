SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.CUSTOMER', 'status') IS NULL
BEGIN
  ALTER TABLE dbo.CUSTOMER
    ADD status nvarchar(20) NOT NULL
      CONSTRAINT DF_CUSTOMER_status DEFAULT('ACTIVE') WITH VALUES;
END;

IF NOT EXISTS (
  SELECT 1 FROM sys.check_constraints
  WHERE parent_object_id = OBJECT_ID('dbo.CUSTOMER') AND name = 'CK_CUSTOMER_status'
)
BEGIN
  EXEC(N'ALTER TABLE dbo.CUSTOMER WITH CHECK
    ADD CONSTRAINT CK_CUSTOMER_status CHECK(status IN(''ACTIVE'',''INACTIVE''));');
END;

IF NOT EXISTS (
  SELECT 1 FROM sys.indexes
  WHERE object_id = OBJECT_ID('dbo.CUSTOMER') AND name = 'IX_CUSTOMER_status'
)
BEGIN
  EXEC(N'CREATE INDEX IX_CUSTOMER_status ON dbo.CUSTOMER(status);');
END;

COMMIT;
