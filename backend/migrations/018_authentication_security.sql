SET XACT_ABORT ON;

IF OBJECT_ID('dbo.AUTH_LOGIN_ATTEMPT','U') IS NULL
BEGIN
  CREATE TABLE dbo.AUTH_LOGIN_ATTEMPT (
    subject_hash char(64) NOT NULL CONSTRAINT PK_AUTH_LOGIN_ATTEMPT PRIMARY KEY,
    attempts int NOT NULL CONSTRAINT CK_AUTH_LOGIN_ATTEMPT_count CHECK(attempts BETWEEN 1 AND 5),
    window_started_at datetime2 NOT NULL,
    blocked_until datetime2 NULL
  );
  CREATE INDEX IX_AUTH_LOGIN_ATTEMPT_window ON dbo.AUTH_LOGIN_ATTEMPT(window_started_at) INCLUDE(blocked_until);
END;

IF OBJECT_ID('dbo.AUTH_SECURITY_EVENT','U') IS NULL
BEGIN
  CREATE TABLE dbo.AUTH_SECURITY_EVENT (
    event_id bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_AUTH_SECURITY_EVENT PRIMARY KEY,
    principal_type varchar(8) NOT NULL CONSTRAINT CK_AUTH_SECURITY_EVENT_role CHECK(principal_type IN('CUSTOMER','ADMIN')),
    principal_id int NULL,
    subject_hash char(64) NOT NULL,
    ip_hash char(64) NULL,
    event_type varchar(24) NOT NULL CONSTRAINT CK_AUTH_SECURITY_EVENT_type CHECK(event_type IN('LOGIN_SUCCESS','LOGIN_FAILED','LOGIN_THROTTLED','LOGOUT','LOGOUT_ALL','PASSWORD_RESET')),
    created_at datetime2 NOT NULL CONSTRAINT DF_AUTH_SECURITY_EVENT_created DEFAULT(SYSUTCDATETIME())
  );
  CREATE INDEX IX_AUTH_SECURITY_EVENT_created ON dbo.AUTH_SECURITY_EVENT(created_at);
END;

IF COL_LENGTH('dbo.ADMIN_SESSION','last_seen_at') IS NULL
  ALTER TABLE dbo.ADMIN_SESSION ADD last_seen_at datetime2 NOT NULL
    CONSTRAINT DF_ADMIN_SESSION_last_seen DEFAULT(SYSUTCDATETIME()) WITH VALUES;
